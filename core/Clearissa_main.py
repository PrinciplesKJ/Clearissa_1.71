class MainApplication(QTabWidget):
    """Main application window with tabbed interface for data analysis tools."""

    def __init__(self):
        super().__init__()
        self._setup_window()
        self._initialise_components()
        self._create_tabs()
        self._apply_styling()
        self._connect_signals()
        # Don't populate manual on startup—only when tab is accessed

    def _setup_window(self):
        """Configure main window properties and tab change tracking."""
        self.setWindowTitle(APP_NAME)
        self.setMinimumSize(1200, 720)
        self.setTabPosition(QTabWidget.North)
        self.previous_tab_index = None
        self.currentChanged.connect(self.on_tab_changed)

    def _initialise_components(self):
        """Initialise core application components and establish inter-component references."""
        self.settings_manager = SettingsManager()
        self.optionsproc = OptionsPanel()
        self.data_loader = CSVDataLoader(self)
        self.dataproc = DataFrameProcessor(self, self.data_loader, self.optionsproc)
        self.data_loader.dataproc = self.dataproc
        self.kineticproc = None  # Created on demand

    def _create_tabs(self):
        """Create and configure all application tabs."""
        self._create_main_tab()
        # Don't create View Data tab initially—it will be created when needed
        self._create_options_tab()

        # Store reference for lazy tab creation
        self.view_data_tab = None

    def _create_main_tab(self):
        """Create the main landing tab using WelcomePanel."""
        self.welcome_panel = WelcomePanel(APP_VERSION)
        self.addTab(self.welcome_panel, "Main")

    def _connect_signals(self):
        """Connect signals from welcome panel to their respective handlers."""
        self.welcome_panel.load_folder_clicked.connect(self.data_loader.load_csv_folder)
        self.welcome_panel.view_data_clicked.connect(self.switch_to_view_data_tab)
        self.welcome_panel.kinetics_clicked.connect(self.switch_to_kinetics_tab)
        self.welcome_panel.manual_clicked.connect(self.open_manual)
        self.welcome_panel.options_clicked.connect(self.switch_to_options_tab)

    def _create_view_data_tab(self):
        """Create the data viewing tab on demand."""
        if self.view_data_tab is None:
            self.view_data_tab = QWidget()
            self.view_data_layout = QVBoxLayout(self.view_data_tab)
            self.addTab(self.view_data_tab, "View Data")


    def _create_options_tab(self):
        """Create the options configuration tab."""
        self.options_tab = QWidget()
        options_layout = QVBoxLayout(self.options_tab)
        options_layout.addWidget(self.optionsproc)
        self.addTab(self.options_tab, "Options")

    def _apply_styling(self):
        """Apply custom CSS styling to the tab widget."""
        self.setStyleSheet("""
            QTabWidget::pane {
                border: 1px solid #9E9E9E;
                top: -1px;
            }
            QTabBar::tab {
                background-color: #E0E0E0;
                border: 1px solid #9E9E9E;
                border-top-left-radius: 4px;
                border-top-right-radius: 4px;
                padding: 6px 12px;
                color: #212121;
            }
            QTabBar::tab:selected {
                background-color: #BDBDBD;
                border-bottom-color: #BDBDBD;
                color: #212121;
            }
            QTabBar::tab:!selected {
                margin-top: 2px;
            }
        """)

    def switch_to_options_tab(self):
        """Switch to the options configuration tab."""
        self.setCurrentWidget(self.options_tab)

    def switch_to_view_data_tab(self):
        """Switch to the data viewing tab and initialise the data window if needed."""
        self._create_view_data_tab()  # Create if doesn't exist
        self.setCurrentWidget(self.view_data_tab)
        # Only initialise if the tab is empty
        if self.view_data_layout.count() == 0:
            self.dataproc.view_data_window()

    def switch_to_kinetics_tab(self):
        """Switch to the kinetics analysis tab, creating it if necessary."""
        # Clean up existing kinetics tab if present
        if hasattr(self, 'kinetics_tab') and self.indexOf(self.kinetics_tab) != -1:
            if self.kineticproc is not None:
                self.kinetics_tab.layout().removeWidget(self.kineticproc)
                self.kineticproc.deleteLater()
                self.kineticproc = None
            self.removeTab(self.indexOf(self.kinetics_tab))

        # Create new kinetics tab
        self.kinetics_tab = QWidget()
        kinetics_layout = QVBoxLayout(self.kinetics_tab)
        self.kineticproc = KineticsProcessor()
        self.kineticproc.init_ui()  # Initialise UI before adding to layout
        
        # Automatically restore last saved state
        self.kineticproc.restore_state()
        
        kinetics_layout.addWidget(self.kineticproc)
        self.addTab(self.kinetics_tab, "Kinetics")
        self.setCurrentWidget(self.kinetics_tab)


    def open_manual(self):
        """
        Open the user manual HTML file in the system's default web browser.

        Handles both development and PyInstaller frozen environments.
        """
        try:
            manual_path = get_resource_path("manual.html")

            # Convert to absolute path and use file:// URL
            manual_path = os.path.abspath(manual_path)

            # Check if file exists
            if not os.path.exists(manual_path):
                logging.error(f"Manual file not found at: {manual_path}")
                from PyQt5.QtWidgets import QMessageBox
                QMessageBox.warning(
                    self,
                    "Manual Not Found",
                    f"The user manual file could not be found at:\n{manual_path}"
                )
                return

            # Open in default browser
            # Use file:/// protocol (three slashes for absolute paths on Windows)
            if sys.platform == 'win32':
                # Windows requires special handling for file URLs
                file_url = f"file:///{manual_path.replace(os.sep, '/')}"
            else:
                file_url = f"file://{manual_path}"

            webbrowser.open(file_url)
            logging.info(f"Opened manual in browser: {manual_path}")

        except Exception as e:
            logging.error(f"Failed to open manual: {e}")
            from PyQt5.QtWidgets import QMessageBox
            QMessageBox.critical(
                self,
                "Error Opening Manual",
                f"Failed to open the user manual:\n{str(e)}"
            )

    def on_tab_changed(self, new_index):
        """Handle tab change events and save state of previous tab if applicable."""
        if self.previous_tab_index is not None:
            previous_tab = self.widget(self.previous_tab_index)
            if hasattr(previous_tab, "save_state"):
                previous_tab.save_state()
            # Save kinetics processor state when switching away from it
            if hasattr(self, 'kineticproc') and self.kineticproc is not None:
                if previous_tab == self.kinetics_tab:
                    self.kineticproc.save_state()
            # Save dataprocessor state when switching away from View Data tab
            if hasattr(self, 'dataproc') and self.dataproc is not None:
                if hasattr(self, 'view_data_tab') and previous_tab == self.view_data_tab:
                    self.dataproc.save_state()
        self.previous_tab_index = new_index

    def closeEvent(self, event):
        """Handle application closure by saving all tab states."""
        # Save data processor state
        if hasattr(self, 'dataproc') and self.dataproc is not None:
            self.dataproc.save_state()

        # Save kinetics processor state if it exists
        if hasattr(self, 'kineticproc') and self.kineticproc is not None:
            self.kineticproc.save_state()

        # Save state for all tabs that support it
        for index in range(self.count()):
            tab = self.widget(index)
            if hasattr(tab, "save_state"):
                tab.save_state()

        super().closeEvent(event)


