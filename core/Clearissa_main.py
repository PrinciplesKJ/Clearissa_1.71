def setup_logging():
    """
    Configure application-wide logging system.

    Creates log directory if needed and configures dual output to both
    file and console with consistent formatting.

    Handles both development and PyInstaller frozen environments.

    Returns
    -------
    None

    Notes
    -----
    Log file location:
    - Windows: C:\\Users\\<username>\\AppData\\Roaming\\Clearissa\\log\\clearissa.log
    - Linux/macOS: ~/.clearissa/log/clearissa.log

    Log level: INFO for both file and console handlers
    Format: timestamp - level - message
    """
    try:
        # Use resource_utils to get proper log directory
        log_dir = get_log_dir()
        log_file = log_dir / "clearissa.log"

        # Create formatter
        formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")

        # Get root logger
        logger = logging.getLogger()
        logger.setLevel(logging.INFO)

        # Create file handler
        file_handler = logging.FileHandler(str(log_file), mode='a')
        file_handler.setLevel(logging.INFO)
        file_handler.setFormatter(formatter)

        # Create console handler
        console_handler = logging.StreamHandler()
        console_handler.setLevel(logging.INFO)
        console_handler.setFormatter(formatter)

        # Add both handlers to root logger
        logger.addHandler(file_handler)
        logger.addHandler(console_handler)

        print(f"Logging enabled - writing to {log_file} and console")
        logging.info("==================================================")
        logging.info("APPLICATION STARTED - CLEARISSA v%s", APP_VERSION)
        logging.info("Running mode: %s", "FROZEN (Compiled)" if getattr(sys, 'frozen', False) else "DEVELOPMENT")
        logging.info("==================================================")
    except Exception as e:
        print(f"Logging setup failed: {e} - continuing without logging")


